"""Writes manifest.h: every file the game reads from the disc (path, size), its empty folders, and the SHA-256 of
default.xbe, taken from a known-good copy of the game files.
The empty folders matter: without media/sounds the game loses its sound effects and voices.
usage: python installer/gen_manifest.py game"""
import hashlib
import sys
from pathlib import Path

root = Path(sys.argv[1])
skip = {"mvc2_analysis.json"}          # a recompiler artifact, not on the disc
files = sorted((p.relative_to(root).as_posix(), p.stat().st_size) for p in root.rglob("*")
               if p.is_file() and p.name not in skip)
empty = sorted(p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_dir() and not any(p.iterdir()))
digest = hashlib.sha256((root / "default.xbe").read_bytes()).digest()
out = ["/* generated by gen_manifest.py; do not edit */",
       "static const unsigned char XBE_SHA256[32] = {" + ",".join(str(b) for b in digest) + "};",
       "static const struct { const char *path; unsigned long long size; } MANIFEST[] = {"]
out += [f'    {{ "{p}", {s}ULL }},' for p, s in files]
out += ["};", "static const char *const MANIFEST_EMPTY_DIRS[] = {"]
out += [f'    "{p}",' for p in empty]
out += ["};", f"#define MANIFEST_COUNT {len(files)}",
        f"#define MANIFEST_BYTES {sum(s for _, s in files)}ULL", ""]
Path(__file__).with_name("manifest.h").write_text("\n".join(out), encoding="utf-8")
print(len(files), "files", sum(s for _, s in files), "empty folders", empty)
