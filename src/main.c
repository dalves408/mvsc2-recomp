/* The player build (cmake -DMVC2_RELEASE=ON). The game files sit next to the exe, whatever folder it was started from;
 * saves and settings go to %LOCALAPPDATA%\MvC2Recomp; the developer switches (RECOMP_*) from outside are ignored. */
static char s_player_ini[MAX_PATH];     /* settings.ini: [display] fullscreen, window_scale (config.exe writes it too) */
static char s_partition_dir[MAX_PATH];  /* the emulated disk's sparse images, kept out of SaveData */

static void player_save_fullscreen(int fullscreen)
{
    WritePrivateProfileStringA("display", "fullscreen", fullscreen ? "1" : "0", s_player_ini);
}

static void player_setup(void)
{
    extern void (*xbox_fb_fullscreen_changed)(int);
    char path[MAX_PATH], base[MAX_PATH], *slash;
    const char *mode;
    int fullscreen, scale;

    if (GetModuleFileNameA(NULL, path, MAX_PATH) && (slash = strrchr(path, '\\')) != NULL) {
        *slash = 0;
        SetCurrentDirectoryA(path);
    }
    for (;;) {      /* removing a variable changes _environ, so start over each time */
        char name[128];
        char **e;
        for (e = _environ; *e; e++)
            if (!strncmp(*e, "RECOMP_", 7) && strchr(*e, '=') && (size_t)(strchr(*e, '=') - *e) < sizeof name)
                break;
        if (!*e)
            break;
        snprintf(name, sizeof name, "%.*s", (int)(strchr(*e, '=') - *e), *e);
        _putenv_s(name, "");
    }
    if (!GetEnvironmentVariableA("LOCALAPPDATA", base, sizeof base) || strlen(base) > MAX_PATH - 60)
        strcpy(base, ".");
    snprintf(path, sizeof path, "%s\\MvC2Recomp", base);
    CreateDirectoryA(path, NULL);
    mvc2_diag_log_start(path);          /* from here on everything printed is also in MvC2Recomp\logs */
    snprintf(s_player_ini, sizeof s_player_ini, "%s\\MvC2Recomp\\settings.ini", base);
    snprintf(s_partition_dir, sizeof s_partition_dir, "%s\\MvC2Recomp\\Partitions", base);
    snprintf(path, sizeof path, "%s\\MvC2Recomp\\SaveData", base);
    _putenv_s("RECOMP_SAVE_DIR", path);
    _putenv_s("RECOMP_NO_KERNEL_LOG", "1");
    _putenv_s("RECOMP_FB_PLAIN_TITLE", "Marvel vs. Capcom 2");

    /* RecompLauncher's Big Picture mode always gets fullscreen, and the saved setting stays as it is. "desktop" or no
     * launcher: the saved setting, which F11 and Alt+Enter keep up to date. */
    mode = getenv("RECOMPLAUNCHER_MODE");
    fullscreen = (mode && !_stricmp(mode, "bigpicture"))
        || GetPrivateProfileIntA("display", "fullscreen", 1, s_player_ini) != 0;
    if (fullscreen)
        _putenv_s("RECOMP_FULLSCREEN", "1");
    scale = GetPrivateProfileIntA("display", "window_scale", 2, s_player_ini);
    if (scale >= 1 && scale <= 4) {
        snprintf(path, sizeof path, "%d", scale);
        _putenv_s("RECOMP_WINDOW_SCALE", path);
    }
    xbox_fb_fullscreen_changed = player_save_fullscreen;
}
